def slug(s):
    s = s.replace("++", " plus plus").replace("#", " sharp").replace(".NET", "dotnet").replace(".", " dot ")
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or "skill"

rows, seen = [], set()
def add(cname, alias, label, source):
    n = normalize_text(alias)
    if not n or n in seen: return
    seen.add(n)
    rows.append({"canonical_skill_id": slug(cname), "canonical_skill_name": cname, "alias": alias,
                 "normalized_alias": n, "taxonomy": "CUSTOM", "label": label, "label_hint": label, "source": source})
for cname, (label, aliases) in CURATED.items():
    for a in dict.fromkeys([cname] + aliases):
        add(cname, a, label, "library_curated")
for cname, alias, label in MANUAL_ALIAS_PAIRS:
    add(cname, alias, label, "manual_curated")
out = "src/skillllm_v2/resources/offline_aliases.jsonl"
