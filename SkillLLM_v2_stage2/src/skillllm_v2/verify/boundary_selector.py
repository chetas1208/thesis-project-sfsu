"""boundary_selector.py

Dev-calibrated selector that picks the final span for a Raw Mistral (or other
source) candidate from the set of boundary-edit variants generated by
:class:`skillllm_v2.verify.boundary_refiner.BoundaryRefiner`.

Design goal: be conservative. The original (unedited) span always wins unless
a candidate variant has *strong evidence* (exact taxonomy/alias match, allowed
edit type, and a score margin over the original that exceeds a label-specific
threshold). This is the fix for the destructive boundary refiner that
previously replaced every span unconditionally and dropped Exact Span F1 from
0.675 to 0.570.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

from skillllm_v2.config import load_yaml
from skillllm_v2.normalize.skill_alias_builder import build_alias_index, load_alias_records
from skillllm_v2.schema import normalize_text

DEFAULT_TUNED_CONFIG_PATH = "artifacts/skillllm_v2/boundary_refiner/tuned_config.yaml"

GENERIC_FILLER_WORDS = {
    "the", "a", "an", "of", "with", "and", "or", "in", "on", "for", "to",
    "strong", "excellent", "good", "great", "team", "skills", "skill",
    "experience", "knowledge", "tools", "technologies", "models",
}

DEFAULT_CONFIG: dict[str, Any] = {
    # Base score per edit type. "original" is the no-edit baseline (score 0.0).
    "edit_type_scores": {
        "original": 0.0,
        "trim_leading_filler": 0.05,
        "trim_trailing_filler": -0.20,
        "head_skill": -0.20,
        "split_conjunction": -0.20,
        "taxonomy_normalized": 0.20,
        "realign_word_boundary": 0.25,
    },
    # Edit types the selector is allowed to choose (besides "original").
    # Trailing trims / head-skill / conjunction splits are disabled by default
    # because they were the dominant cause of the soft-skill F1 collapse.
    "allowed_edit_types": ["trim_leading_filler", "taxonomy_normalized", "realign_word_boundary"],
    # Bonus applied to a variant whose normalized surface form is an exact
    # alias/taxonomy match.
    "alias_evidence_bonus": 0.30,
    # Penalty applied when an edit removes a substring that is itself an
    # alias-table entry (i.e. the edit may be discarding a real skill term).
    "removed_skill_term_penalty": 0.25,
    # Penalty weight per filler-word-only token retained/removed.
    "filler_ratio_penalty_weight": 0.10,
    # Penalty weight per token of length change between original and candidate.
    "length_change_penalty_weight": 0.02,
    # Maximum number of tokens a trim/head edit may remove.
    "max_trim_tokens": 2,
    # Minimum score margin (candidate - original) required to replace the
    # original span, by label.
    "label_thresholds": {
        "HARD_SKILL": {"min_margin_to_replace": 0.08},
        "SOFT_SKILL": {"min_margin_to_replace": 0.15},
    },
    "default_min_margin_to_replace": 0.10,
}


def _deep_merge(base: dict[str, Any], override: dict[str, Any]) -> dict[str, Any]:
    merged = dict(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = _deep_merge(merged[key], value)
        else:
            merged[key] = value
    return merged


def load_selector_config(tuned_config_path: str | None = DEFAULT_TUNED_CONFIG_PATH) -> dict[str, Any]:
    config = {k: (dict(v) if isinstance(v, dict) else list(v) if isinstance(v, list) else v) for k, v in DEFAULT_CONFIG.items()}
    if tuned_config_path and Path(tuned_config_path).exists():
        tuned = load_yaml(tuned_config_path)
        config = _deep_merge(config, tuned.get("boundary_selector", tuned))
    return config


class BoundarySelector:
    def __init__(self, config: dict[str, Any] | None = None, alias_paths: list[str] | None = None, tuned_config_path: str | None = DEFAULT_TUNED_CONFIG_PATH) -> None:
        self.config = config or load_selector_config(tuned_config_path)
        self.alias_index = build_alias_index(load_alias_records(alias_paths))

    def _alias_evidence(self, surface: str) -> dict[str, Any] | None:
        return self.alias_index.get(normalize_text(surface))

    def _margin(self, label: str) -> float:
        return float(self.config["label_thresholds"].get(label, {}).get("min_margin_to_replace", self.config["default_min_margin_to_replace"]))

    def score_variant(self, original_surface: str, variant: dict[str, Any]) -> float:
        edit_type = variant["edit_type"]
        score = float(self.config["edit_type_scores"].get(edit_type, -1.0))
        score += float(variant.get("confidence_delta", 0.0))

        candidate_surface = variant["candidate_surface_form"]
        if self._alias_evidence(candidate_surface) is not None:
            score += float(self.config["alias_evidence_bonus"])

        # Penalize variants that drop a substring which is itself a known skill term.
        removed = _removed_text(original_surface, candidate_surface)
        if removed and self._alias_evidence(removed) is not None:
            score -= float(self.config["removed_skill_term_penalty"])

        # Penalize candidates dominated by generic filler tokens.
        cand_tokens = candidate_surface.lower().split()
        if cand_tokens:
            filler_ratio = sum(1 for tok in cand_tokens if tok.strip(",.;:") in GENERIC_FILLER_WORDS) / len(cand_tokens)
            score -= filler_ratio * float(self.config["filler_ratio_penalty_weight"])

        # Penalize large length changes.
        orig_tokens = original_surface.split()
        token_diff = abs(len(orig_tokens) - len(cand_tokens))
        score -= token_diff * float(self.config["length_change_penalty_weight"])

        return score

    def select(self, text: str, candidate: dict[str, Any], variants: list[dict[str, Any]]) -> list[dict[str, Any]]:
        if candidate.get("start") is None or not variants:
            return [candidate]

        original_surface = candidate["surface_form"]
        max_trim = int(self.config["max_trim_tokens"])
        allowed = set(self.config["allowed_edit_types"]) | {"original"}

        # Group variants by their resulting span set (dedup identical edits
        # produced by multiple edit types), keeping the highest-scoring one.
        best_by_spans: dict[tuple[tuple[int, int, str], ...], dict[str, Any]] = {}
        best_score_by_spans: dict[tuple[tuple[int, int, str], ...], float] = {}

        original_variant = next((v for v in variants if v["edit_type"] == "original"), None)
        if original_variant is None:
            return [candidate]
        original_score = self.score_variant(original_surface, original_variant)

        for variant in variants:
            edit_type = variant["edit_type"]
            if edit_type not in allowed:
                continue
            if edit_type != "original":
                removed_tokens = abs(len(original_surface.split()) - len(variant["candidate_surface_form"].split()))
                if edit_type in {"trim_leading_filler", "trim_trailing_filler", "head_skill"} and removed_tokens > max_trim:
                    continue
            spans_key = tuple((s["start"], s["end"], s["surface_form"]) for s in variant["spans"])
            score = self.score_variant(original_surface, variant)
            if spans_key not in best_score_by_spans or score > best_score_by_spans[spans_key]:
                best_score_by_spans[spans_key] = score
                best_by_spans[spans_key] = variant

        if not best_by_spans:
            return [candidate]

        best_spans_key, best_variant = max(best_by_spans.items(), key=lambda kv: best_score_by_spans[kv[0]])
        best_score = best_score_by_spans[best_spans_key]

        if best_variant["edit_type"] == "original":
            chosen = original_variant
        elif (best_score - original_score) >= self._margin(candidate["label"]):
            chosen = best_variant
        else:
            chosen = original_variant

        return _materialize(text, candidate, chosen)


def _removed_text(original_surface: str, candidate_surface: str) -> str:
    original_norm = original_surface.strip()
    candidate_norm = candidate_surface.strip()
    if candidate_norm and candidate_norm in original_norm:
        if original_norm.startswith(candidate_norm):
            return original_norm[len(candidate_norm):].strip(" ,.;:")
        if original_norm.endswith(candidate_norm):
            return original_norm[: -len(candidate_norm)].strip(" ,.;:")
    return ""


def _materialize(text: str, candidate: dict[str, Any], variant: dict[str, Any]) -> list[dict[str, Any]]:
    spans = variant["spans"]
    edit_record = {
        "original_surface_form": variant["original_surface_form"],
        "candidate_surface_form": variant["candidate_surface_form"],
        "original_start": variant["original_start"],
        "original_end": variant["original_end"],
        "candidate_start": variant["candidate_start"],
        "candidate_end": variant["candidate_end"],
        "edit_type": variant["edit_type"],
        "edit_reason": variant["edit_reason"],
        "confidence_delta": variant["confidence_delta"],
        "source": "boundary_refiner",
    }

    output: list[dict[str, Any]] = []
    for span in spans:
        item = dict(candidate)
        item["surface_form"] = span["surface_form"]
        item["start"] = span["start"]
        item["end"] = span["end"]
        item["evidence"] = span["surface_form"]
        item["confidence"] = min(1.0, max(0.0, float(candidate["confidence"]) + float(variant.get("confidence_delta", 0.0))))
        item["metadata"] = dict(candidate.get("metadata") or {})
        item["metadata"]["boundary_edit"] = dict(edit_record)
        if len(spans) > 1:
            item["metadata"]["boundary_edit"]["candidate_surface_form"] = span["surface_form"]
            item["metadata"]["boundary_edit"]["candidate_start"] = span["start"]
            item["metadata"]["boundary_edit"]["candidate_end"] = span["end"]
        output.append(item)
    return output
